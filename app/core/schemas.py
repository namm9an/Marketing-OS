"""
Pydantic v2 Data Schemas & Input/Output Validation Contracts.

Enforces runtime contracts for grounded knowledge units, persistent decisions,
tiered memories (L0-L2), multi-turn chat turns, specialist agent outputs,
triage bridge synthesis, and executive digests.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class SchemaBase(BaseModel):
    model_config = ConfigDict(extra="ignore", populate_by_name=True)


class KnowledgeUnitSchema(SchemaBase):
    """L0 Grounded knowledge unit scraped from competitor and market sources."""

    id: str = Field(..., description="Unique 128-bit hex UUID4 or deterministic SHA-256 identifier")
    organization: str = Field(..., description="Entity or competitor name (e.g. Vanguard Cloud, Nebius)")
    knowledge_class: str = Field(
        ...,
        description="Fact taxonomy class: pricing, hardware fleet, positioning, compliance, etc.",
    )
    confidence: str = Field(default="high", description="Source confidence level (high, medium, low)")
    content: str = Field(..., description="Empirical factual statement")
    source_url: Optional[str] = Field(default=None, description="Cryptographic provenance URL")
    enriched_by: str = Field(default="system", description="Provenance creator or crawler component")
    created_at: Optional[str] = Field(default=None, description="ISO-8601 creation timestamp")


class DecisionRecordSchema(SchemaBase):
    """Persistent CMO strategic decision generated by agent workflows."""

    id: str = Field(..., description="Unique 128-bit hex UUID4 identifier")
    goal_statement: str = Field(..., description="Input marketing or positioning goal")
    selected_option: str = Field(..., description="Selected strategic option title")
    confidence: str = Field(default="High", description="Agent confidence rating: High, Medium, Low")
    escalated: bool = Field(default=False, description="Whether human CMO governance escalation was triggered")
    reasoning_source: str = Field(..., description="Originating agent or governance engine")
    rationale: str = Field(..., description="Strategic reasoning grounded in evidence")
    risks: str = Field(..., description="Identified competitive risks or counter-measures")
    created_at: Optional[str] = Field(default=None, description="ISO-8601 creation timestamp")


class MemoryRecordSchema(SchemaBase):
    """Tiered memory record (L0 corpus, L1 private agent, L2 joint triage)."""

    id: str = Field(..., description="Unique memory identifier")
    namespace: str = Field(
        ...,
        description="Memory isolation namespace (corpus:global, agent:<type>, triage:<a+b>)",
    )
    tier: str = Field(default="episodic", description="Memory lifecycle tier: episodic, semantic")
    content: str = Field(..., description="Memory content payload")
    provenance: str = Field(default="", description="Turn or user action that created this memory")
    confidence: str = Field(default="medium", description="Confidence level: high, medium, low")
    source_turn_id: Optional[str] = Field(default=None, description="Originating conversation turn ID")
    hit_count: int = Field(default=0, description="Usage and retrieval frequency counter")
    created_at: Optional[str] = Field(default=None, description="ISO-8601 creation timestamp")
    last_used_at: Optional[str] = Field(default=None, description="ISO-8601 last retrieval timestamp")


class AgentResponseSchema(SchemaBase):
    """Structured response contract for specialist agents."""

    selected_option: str = Field(..., description="Short title of strategy option")
    statement: str = Field(..., description="Core positioning or strategic statement")
    rationale: str = Field(..., description="Strategic reasoning backed by facts")
    risks: str = Field(..., description="Identified risks or counter-actions")
    confidence: str = Field(default="High", description="Confidence rating: High, Medium, Low")


class ChatTurnSchema(SchemaBase):
    """Single turn in a per-agent conversation thread."""

    thread_id: str = Field(..., description="Conversation thread identifier")
    turn_id: str = Field(..., description="Unique turn identifier")
    agent: str = Field(..., description="Specialist agent identifier")
    role: str = Field(..., description="Speaker role: user or assistant")
    content: str = Field(..., description="Turn text message")
    recalled_memories: List[Dict[str, Any]] = Field(
        default_factory=list, description="Memories recalled for context"
    )
    recalled_facts: List[Dict[str, Any]] = Field(
        default_factory=list, description="Grounded facts retrieved for context"
    )
    created_at: Optional[str] = Field(default=None, description="ISO-8601 timestamp")


class TriageOutputSchema(SchemaBase):
    """Output contract for two-agent joint triage synthesis."""

    success: bool = Field(default=True, description="Execution success status")
    agents: List[str] = Field(..., description="List of the two specialist agents consulted")
    namespace: str = Field(..., description="Joint triage namespace triage:<a+b>")
    thread_id: str = Field(..., description="Triage thread identifier")
    answer: str = Field(..., description="Merged consensus answer for CMO")
    agreements: List[str] = Field(default_factory=list, description="Shared consensus points")
    tensions: List[str] = Field(default_factory=list, description="Identified trade-offs or friction points")
    recommended_action: str = Field(default="", description="Concrete recommended next step")
    views: List[Dict[str, Any]] = Field(
        default_factory=list, description="Individual specialist perspectives"
    )
    memory: Dict[str, Any] = Field(default_factory=dict, description="Memory promotion gate verdict")


# Convenience alias for TriageOutputSchema
TriageResponseSchema = TriageOutputSchema


class DigestSchema(SchemaBase):
    """CMO weekly digest synthesis (prose only — citations come from the DB, not the LLM)."""

    headline: str = Field(..., description="One-line executive headline on competitor movement")
    executive_summary: str = Field(..., description="Short cross-agent summary for the CMO")
    competitor_movements: List[str] = Field(default_factory=list, description="Notable rival moves")
    recommended_actions: List[str] = Field(
        default_factory=list, description="Recommended strategic actions for enterprise"
    )


class RunRequestSchema(SchemaBase):
    """Input payload validation for /api/run endpoint."""

    agent_type: str = Field(default="branding", description="Target specialist agent")
    goal: str = Field(..., description="Goal statement for strategy generation")
    provider: Optional[str] = Field(default=None, description="LLM provider model identifier")


class ThreadSchema(SchemaBase):
    """Conversation thread tracking container."""

    id: str = Field(..., description="Unique thread identifier")
    namespace: str = Field(..., description="Isolation namespace")
    title: str = Field(default="", description="Thread title")
    created_at: Optional[str] = Field(default=None, description="ISO-8601 creation timestamp")


class GraphEdgeSchema(SchemaBase):
    """Corpus entity knowledge graph edge (L0.5)."""

    id: str = Field(..., description="Unique edge identifier")
    src: str = Field(..., description="Source entity (e.g. organization)")
    rel: str = Field(..., description="Predicate relation (e.g. offers, prices)")
    dst: str = Field(..., description="Target entity (e.g. GPU SKU)")
    namespace: str = Field(default="corpus:global", description="Graph isolation namespace")
    provenance: str = Field(default="", description="Provenance metadata JSON or string")
    created_at: Optional[str] = Field(default=None, description="ISO-8601 creation timestamp")


class ChatRequestSchema(SchemaBase):
    """Input payload contract for POST /api/chat."""

    agent: str = Field(default="branding", description="Target specialist agent")
    message: str = Field(..., description="User message prompt")
    thread_id: Optional[str] = Field(default=None, description="Existing conversation thread ID")
    provider: str = Field(default="gemini-3.6-flash", description="LLM provider model")


class TriageRequestSchema(SchemaBase):
    """Input payload contract for POST /api/triage."""

    agents: List[str] = Field(..., description="Pair of specialist agents")
    message: str = Field(..., description="CMO question to triage")
    thread_id: Optional[str] = Field(default=None, description="Existing triage thread ID")
    provider: str = Field(default="gemini-3.6-flash", description="LLM provider model")
